const cache: Record<string, string> = {};

/** SVG del icono, del tamaño de la letra (1em) y del color del texto. */
export function px(name: keyof typeof B | string, label?: string): string {
  const rows = B[name];
  if (!rows) return '';
  if (!cache[name]) {
    let d = '';
    rows.forEach((row, y) => {
      for (let x = 0; x < row.length;) {
        if (row[x] !== '#') { x++; continue; }
        let w = 0;
        while (row[x + w] === '#') w++;
        d += `M${x} ${y}h${w}v1h-${w}z`;
        x += w;
      }
    });
    cache[name] = d;
  }
  const a11y = label ? `role="img" aria-label="${label}"` : 'aria-hidden="true"';
  return `<svg class="px" viewBox="0 0 9 9" shape-rendering="crispEdges" ${a11y}><path fill="currentColor" d="${cache[name]}"/></svg>`;
}

